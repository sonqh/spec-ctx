// Writes src/assets.generated.ts from schemas/spec-driven-ids/ and skills/.
// The contents are base64, so the index of this repo reads no tag or ID inside them.
// Run with: node scripts/gen-assets.mjs [--check]
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "src/assets.generated.ts");

function files(dir) {
  const acc = [];
  for (const n of readdirSync(dir).sort()) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) acc.push(...files(p));
    else acc.push(p);
  }
  return acc;
}

export function render() {
  const lines = [
    "// Generated by scripts/gen-assets.mjs from schemas/spec-driven-ids/ and skills/. Do not edit.",
    "// REQ-SCH-001 REQ-SKL-002",
    "export const ASSETS: Record<string, string> = {",
  ];
  for (const base of ["schemas/spec-driven-ids", "skills"]) {
    for (const p of files(join(root, base))) {
      const rel = relative(root, p).split("\\").join("/");
      lines.push(`  ${JSON.stringify(rel)}: ${JSON.stringify(readFileSync(p).toString("base64"))},`);
    }
  }
  lines.push("};", "");
  return lines.join("\n");
}

const text = render();
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(out, "utf8");
  } catch {}
  if (cur !== text) {
    console.error("src/assets.generated.ts is out of date. Run: node scripts/gen-assets.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log("wrote src/assets.generated.ts");
}
